def assumptions_rows(taxonomy: Taxonomy, factors: ImpactFactors, bbox_uncertainty_pct):
    rows = []
    for mc in taxonomy.classes.values():
        for s in mc.sub_list():
            rows.append(OrderedDict(
                macro=mc.label,
                subcategory=s.label,
                sub_key=s.key,
                ecoinvent_flow=s.ecoinvent_flow or "",
                flow_verified=s.flow_verified,
                mass_model="override " + str(list(s.mass_model)) if s.mass_model and s.mass_model != mass_model_map.get(mc.key)
                else ("class regression" if mc.key in mass_model_map else ""),
                dpr_nominal=s.dpr.nominal if s.dpr else None,
                dpr_low=s.dpr.low if s.dpr and s.dpr.range_reported else None,
                dpr_high=s.dpr.high if s.dpr and s.dpr.range_reported else None,
                dpr_source=s.dpr.source if s.dpr else "",
                stack_count=s.stack_count if s.dpr else None,
                note=s.note or mc.note,
            ))
    general = [
        ("Taxonomy file", str(taxonomy.path or "")),
        ("Impact factor file", str(factors.path or "not found")),
        ("Impact method", factors.method),
        ("Bounding-box uncertainty", f"±{bbox_uncertainty_pct}% per dimension"),
        ("Mass bounds", "PI of the area->mass regression and bbox uncertainty, quadrature within a row"),
        ("Die-area bounds", "scenario: all ICs at low (high) DPR and bbox bound, summed linearly"),
        ("Impact bounds", "row bounds summed linearly (conservative)"),
        ("Die area", "package area x stack_count x DPR"),
    ]
    return rows, general


def write_excel_sheets(writer, records, taxonomy, factors, bbox_uncertainty_pct=0.0):
    """Append the subcategory LCI sheets to an open pandas ExcelWriter."""
    import pandas as pd

    rows, totals, missing = aggregate(records, taxonomy, factors)
    pd.DataFrame(rows).to_excel(writer, index=False, sheet_name="LCI by subcategory")
    pd.DataFrame(records).to_excel(writer, index=False, sheet_name="Components")

    imp = []
    for c, t in totals.items():
        label, unit = factors.categories[c]
        imp.append(OrderedDict(category=label, unit=unit,
                               nominal=t["nom"] if t["covered_rows"] else None,
                               low=t["low"] if t["covered_rows"] else None,
                               high=t["high"] if t["covered_rows"] else None,
                               rows_with_factor=f"{t['covered_rows']}/{t['rows']}"))
    for m in missing:
        imp.append(OrderedDict(category="MISSING", unit="", nominal=None, low=None, high=None, rows_with_factor=m))
    pd.DataFrame(imp, columns=["category", "unit", "nominal", "low", "high", "rows_with_factor"]).to_excel(
        writer, index=False, sheet_name="Impacts")

    a_rows, general = assumptions_rows(taxonomy, factors, bbox_uncertainty_pct)
    pd.DataFrame(a_rows).to_excel(writer, index=False, sheet_name="Assumptions")
    pd.DataFrame(general, columns=["item", "value"]).to_excel(
        writer, index=False, sheet_name="Assumptions", startrow=len(a_rows) + 3)
    return rows, totals, missing


def print_summary(rows, totals, missing, factors):
    print("\n" + "=" * 78)
    print("LCI BY SUBCATEGORY")
    print("=" * 78)
    print(f"  {'class / subcategory':38s} {'n':>4}  {'mass [mg]':>11}  {'die [mm²]':>22}")
    print("  " + "-" * 76)
    for r in rows:
        name = f"{r['macro']} / {r['subcategory']}"[:38]
        mass = f"{r['mass_mg_nom']:11.2f}" if "mass_mg_nom" in r else f"{'':11s}"
        die = (f"{r['die_mm2_nom']:8.2f} [{r['die_mm2_low']:.1f}-{r['die_mm2_high']:.1f}]"
               if "die_mm2_nom" in r else "")
        print(f"  {name:38s} {r['count']:4d}  {mass}  {die:>22}")
    if totals and any(t["covered_rows"] for t in totals.values()):
        print("\n  Impacts (" + factors.method + "):")
        for c, t in totals.items():
            label, unit = factors.categories[c]
            if t["covered_rows"]:
                print(f"    {label:38s} {t['nom']:.4g} [{t['low']:.4g} - {t['high']:.4g}] {unit}"
                      f"  ({t['covered_rows']}/{t['rows']} rows)")
    elif factors.categories:
        print("\n  Impacts not computed: fill config/impact_factors.yaml with your ecoinvent factors.")
    if missing:
        print(f"\n  {len(missing)} missing item(s) listed in the 'Impacts' sheet.")
    print("=" * 78 + "\n")
