"""
Life cycle inventory at subcategory level, and impact calculation.

Pipeline for each detection:

* non-IC components: area -> mass with the regression of the macro class
  (or a subcategory override), with what component_to_mass does;
* ICs (any DPR): package area -> die area with the
  die-to-package ratio of the selected package type;
* both are then mapped to an ecoinvent reference product and, with factors in config/impact_factors.yaml, to impact scores.

Uncertainty conventions (also written to the "Assumptions" sheet):

* mass: within a (class, subcategory) row, per-component half-intervals are
  combined in quadrature, as in component_to_mass (independent sources);
* die area: scenario bounds, every IC at the low (resp. high) end of its DPR
  range and of the bbox uncertainty, summed linearly ;
* impact totals: row bounds summed linearly.
"""

from __future__ import annotations

import math
from collections import OrderedDict
from pathlib import Path

import yaml

from scripts.component_to_mass import (
    mass_bounds_from_coeffs,
    mass_model_map,
    normalize_class_name,
)
from scripts.labels import read_labels
from scripts.taxonomy import UNSPECIFIED, Taxonomy

DEFAULT_FACTORS_PATH = Path(__file__).resolve().parent.parent / "config" / "impact_factors.yaml"

MG_TO_KG = 1e-6
MM2_TO_CM2 = 1e-2


# =============================================================================
# Impact factors
# =============================================================================
class ImpactFactors:
    """Impact factors per ecoinvent flow, read from config/impact_factors.yaml

    Attributes
    ----------
    path : pathlib.Path or None
        File the factors were read from (None if not found)
    method : str
        LCIA method of the factors, e.g. "EF v3.1"
    categories: OrderedDict
        Impact categories as {key: (label, unit)}
        e.g. {"gwp" : ("Climate chang (GWP100)", "kg C02-eq")}.
    flows : float
        Factors per flow, {flow_name : {'basis':'kg', 'gwp': float or None,...}}
    ic_conversion : dict
        For IC flows, {flow_name : {"kg_per_cm2_die": float or None}}
    """
    def __init__(self, raw: dict | None = None, path=None):
        raw = raw or {}
        self.path = Path(path) if path else None
        self.method = raw.get("method", "")
        self.categories = OrderedDict()
        for key, c in (raw.get("categories") or {}).items():
            c = c or {}
            self.categories[key] = (c.get("label", key), c.get("unit", ""))
        self.flows = raw.get("flows") or {}
        self.ic_conversion = raw.get("ic_die_conversion") or {}

    @classmethod
    def load(cls, path=None) -> "ImpactFactors":
        """Load the yaml file containing the impact factors for each flows"""
        path = Path(path) if path else DEFAULT_FACTORS_PATH
        if not path.exists():
            print(f"⚠️  Impact factor file not found ({path}): impacts are not computed.")
            return cls({}, None)
        with open(path, "r", encoding="utf-8") as f:
            return cls(yaml.safe_load(f) or {}, path)

    def basis(self, flow) -> str:
        """Returns the units in which factors are expressed"""
        return str((self.flows.get(flow) or {}).get("basis", "kg"))

    def factor(self, flow, category):
        """Returns the numerical factor of the flow from the category"""
        v = (self.flows.get(flow) or {}).get(category)
        return None if v is None else float(v)

    def kg_per_cm2_die(self, flow):
        """Give the factor of conversion from cm2 to kg of silicon die"""
        v = (self.ic_conversion.get(flow) or {}).get("kg_per_cm2_die")
        return None if v is None else float(v)

    @property
    def has_any_factor(self) -> bool:
        """Returns true if a factor is present for a flow in the category"""
        return any(self.factor(f, c) is not None for f in self.flows for c in self.categories)


# =============================================================================
# Per-detection records
# =============================================================================
def records_from_labels(label_file, class_map, taxonomy: Taxonomy, width_mm, height_mm,
                        bbox_uncertainty_pct=0.0, image_label="", warn=print):
    """Build one LCI ready record per detection of a component in the cropped-board label file.
    
    Parameters
    ----------
    label_file : str
        Path to .txt cropped version of the file generated by the YOLO model grouping all the detected components.
    class_map : dict
        Dictionnary {int:str} mapping the classes' names to a numerical id 
    taxonomy : Taxonomy
        Convention of how we call the different macro and subcategories
    width_mm : float
        Width of the PCB given by the practitioner
    height_mm : float
        Height of the PCB given by the practitioner
    bbox_uncertainty_pct : float
        Symmetric uncertainty on each bbox dimension
    image_label : str
        Name of the image of the PCB
    
    Returns
    -------
    records : OrderedDict
        A list containing all the informations on the component for the LCI :
        image_label, index, class, macro_key, macro_label, sub_key, sub_label, ecoinvent_flow,
        flow_verified?,confidence on the detection, width, height, area, kind = "mass" or "die" or None or "zero_area",
        + :
         - If IC : dpr_nom, dpr_low, dpr_high, dpr_range_reported, dpr_source, stack_count, die_mm2_nom, die_mm2_low, die_mm2_high
         - Non IC : mass_mg_nom, mass_mg_low, mass_mg_high
    """
    f_lo2 = (1.0 - bbox_uncertainty_pct / 100.0) ** 2
    f_hi2 = (1.0 + bbox_uncertainty_pct / 100.0) ** 2
    records = []

    for idx, det in enumerate(read_labels(label_file), start=1):
        name = class_map.get(det["cls"], f"class_{det['cls']}")
        macro = taxonomy.macro(name)
        sub_key = det.get("sub") or UNSPECIFIED
        if macro is not None and sub_key not in macro.subcategories:
            warn(f"⚠️  {image_label} #{idx}: unknown subcategory '{sub_key}' for {name}, using '{UNSPECIFIED}'.")
            sub_key = UNSPECIFIED
        sub = macro.sub(sub_key) if macro else None

        w_mm = abs(det["w"] * float(width_mm))
        h_mm = abs(det["h"] * float(height_mm))
        area = w_mm * h_mm
        rec = OrderedDict(
            image=image_label,
            index=idx,
            model_class=name,
            macro=macro.key if macro else normalize_class_name(name),
            macro_label=macro.label if macro else name,
            sub=sub_key,
            sub_label=sub.label if sub else UNSPECIFIED,
            flow=sub.ecoinvent_flow if sub else None,
            flow_verified=sub.flow_verified if sub else False,
            confidence=det.get("conf", 1.0),
            width_mm=w_mm,
            height_mm=h_mm,
            area_mm2=area,
            kind="none",
        )
        if area <= 0:
            rec["kind"] = "zero_area"
            records.append(rec)
            continue
        a_min, a_max = area * f_lo2, area * f_hi2 # apply uncertainty

        if sub is not None and sub.dpr is not None: # IC
            d, n = sub.dpr, sub.stack_count
            rec.update(
                kind="die",
                dpr_nominal=d.nominal, dpr_low=d.low, dpr_high=d.high,
                dpr_range_reported=d.range_reported, dpr_source=d.source,
                stack_count=n,
                die_mm2_nom=area * n * d.nominal,
                die_mm2_low=a_min * n * d.low,
                die_mm2_high=a_max * n * d.high,
            )
        else: # Non-IC
            coeffs = (sub.mass_model if sub and sub.mass_model else
                      mass_model_map.get(macro.key if macro else normalize_class_name(name)))
            if coeffs is not None:
                b = mass_bounds_from_coeffs(coeffs, a_min, area, a_max)
                rec.update(kind="mass", mass_mg_nom=b["nom"],
                           mass_mg_low=b["combined_low"], mass_mg_high=b["combined_high"])
        records.append(rec)
    return records


# =============================================================================
# Aggregation and impacts
# =============================================================================
def _quad_bounds(noms, lows, highs):
    """Additionne les valeurs nominales et combine les demi intervalles en quadrature"""
    nom = sum(noms)
    lo = math.sqrt(sum((n - l) ** 2 for n, l in zip(noms, lows)))
    hi = math.sqrt(sum((h - n) ** 2 for n, h in zip(noms, highs)))
    return nom, max(0.0, nom - lo), nom + hi


def aggregate(records, taxonomy: Taxonomy, factors: ImpactFactors):
    """Group records by (macro, subcategory) and compute reference quantities and impacts.

    Returns (rows, totals, missing) where
      rows    : list of OrderedDict, one per (macro, subcategory)
      totals  : {category: {'nom', 'low', 'high', 'covered_rows', 'rows'}}
      missing : list of human-readable strings (flows without factors, ...)
    """
    groups = OrderedDict()
    for macro_key, mc in taxonomy.classes.items():           # gives (key, macroclasses) pairs : 
        for sub_key in mc.subcategories:
            groups[(macro_key, sub_key)] = []
    for r in records:  # range le record "r" dans son groupe
        groups.setdefault((r["macro"], r["sub"]), []).append(r)

    rows, missing = [], []
    cats = list(factors.categories)
    totals = {c: {"nom": 0.0, "low": 0.0, "high": 0.0, "covered_rows": 0, "rows": 0} for c in cats}

    # calculate all the impacts and quantity 
    for (macro_key, sub_key), recs in groups.items():
        if not recs:
            continue
        first = recs[0] # same flow for every record of the same subcategory
        kind = first["kind"]
        row = OrderedDict(
            macro=first["macro_label"],
            subcategory=first["sub_label"],
            sub_key=sub_key,
            ecoinvent_flow=first["flow"] or "",
            flow_verified=first["flow_verified"],
            count=len(recs),
            area_mm2=sum(r["area_mm2"] for r in recs),
            basis=kind,
        )
        # split in this group which one has mass and which one has area of die
        mass_recs = [r for r in recs if r["kind"] == "mass"]
        die_recs = [r for r in recs if r["kind"] == "die"]
        qty_unit, qty = "", None

        # calculate the boundaries of the mass type components
        if mass_recs:
            nom, lo, hi = _quad_bounds([r["mass_mg_nom"] for r in mass_recs],
                                       [r["mass_mg_low"] for r in mass_recs],
                                       [r["mass_mg_high"] for r in mass_recs])
            row.update(mass_mg_nom=nom, mass_mg_low=lo, mass_mg_high=hi)
            qty_unit, qty = "kg", (nom * MG_TO_KG, lo * MG_TO_KG, hi * MG_TO_KG)

        # sums of the (nominal, low, high) die area and note the used DPR
        if die_recs:
            die = tuple(sum(r[k] for r in die_recs) for k in ("die_mm2_nom", "die_mm2_low", "die_mm2_high"))
            d = first
            row.update(
                die_mm2_nom=die[0], die_mm2_low=die[1], die_mm2_high=die[2],
                dpr=f"{d['dpr_nominal']:.1%}" + (f" [{d['dpr_low']:.0%}-{d['dpr_high']:.0%}]"
                                                 if d["dpr_range_reported"] else " (no range reported)"),
                stack_count=d["stack_count"],
            )
            flow = first["flow"]
            if factors.basis(flow) == "die_cm2":
                qty_unit, qty = "cm2 die", tuple(x * MM2_TO_CM2 for x in die)
            else:
                k = factors.kg_per_cm2_die(flow)
                if k is not None:
                    qty_unit, qty = "kg", tuple(x * MM2_TO_CM2 * k for x in die)
                elif cats:
                    missing.append(f"{flow}: no die-area conversion (ic_die_conversion.kg_per_cm2_die)")

        unmodelled = [r for r in recs if r["kind"] in ("none", "zero_area")]
        if unmodelled:
            row["note"] = f"{len(unmodelled)} without mass model"

        if qty is not None:
            row.update(ref_unit=qty_unit, ref_qty_nom=qty[0], ref_qty_low=qty[1], ref_qty_high=qty[2])

        for c in cats:
            totals[c]["rows"] += 1
            cf = factors.factor(first["flow"], c) if first["flow"] else None
            if qty is None or cf is None:
                continue
            vals = (qty[0] * cf, qty[1] * cf, qty[2] * cf)
            row[f"{c}_nom"], row[f"{c}_low"], row[f"{c}_high"] = vals
            totals[c]["nom"] += vals[0]
            totals[c]["low"] += min(vals[1], vals[2])
            totals[c]["high"] += max(vals[1], vals[2])
            totals[c]["covered_rows"] += 1

        if cats and first["flow"] and all(factors.factor(first["flow"], c) is None for c in cats):
            missing.append(f"{first['flow']}: no factor")
        if not first["flow"]:
            missing.append(f"{first['macro_label']} / {first['sub_label']}: no ecoinvent flow defined")
        rows.append(row)

    missing = list(OrderedDict.fromkeys(missing)) # delete copies 
    return rows, totals, missing


